import { chromium, devices } from '@playwright/test';
const browser = await chromium.launch();
const p = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage();
p.on('console', (c) => console.log('console', c.type(), c.text()));
p.on('pageerror', (e) => console.log('pageerror', e.message));
p.on('response', (r) => r.status() >= 400 && console.log('http', r.status(), r.url()));
await p.goto(process.argv[2]);
await p.waitForTimeout(2500);
console.log((await p.textContent('body')).slice(0, 400));
await browser.close();
